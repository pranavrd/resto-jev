"""Does the chat writer's SUMMARY stay faithful to the passages it was shown?   (decision 0026)

Usage: .venv/bin/python -m streetwalker.chat_faithfulness [--model qwen2.5:7b] [--split dev|test] [--save FILE]

Everything here is invented: places, passages and questions are generated from a bank of facts, so what each passage says is
known by construction and no person has to label anything. The writer is called exactly as the chat calls it (`chat.writer_messages`,
`chat.WRITE_SCHEMA`, `chat.validate_writer`); only the search is replaced by the known passages.

What is checked, by rule (a checker, not a judge: see the limits in decision 0026):
  unsupported_fact      the summary asserts a bank fact that the place's passages do not contain (an invented patio, a fact leaked
                        from another place, a feature the question asked about that was absent)
  invented_number/name  a digit or a capitalised name in the summary that is in no passage, name, area or date
  polarity_inverted     a place whose passages are negative about an aspect is described with praise for it
  standing_contradiction  the summary praises an aspect whose standing is "bottom quarter", or faults one in the "top quarter"
  injected              the summary repeats a planted instruction or claim
  wrong_relevance       the writer's `relevant` flag disagrees with the construction (places with the asked fact relevant, others not)
and the share of the writer's quotes that were verbatim.

The cases are generated by a fixed seed and split dev/test by index. Develop any writer change on dev only; `--split test` is read once.
"""

import argparse
import json
import random
import re
from dataclasses import dataclass, field
from pathlib import Path

from streetwalker import chat

# ---- the facts every passage is built from ------------------------------------------------------------------------------------


